"""
exp_2_run.py
============
Experiment runner for exp_2: liquid-universe extension of the microcap
insider-purchase disclosure study.

Runs the full :mod:`src.liquid_universe_extension` pipeline, saves results
to ``results/exp2/``, and prominently reports the matched-control support
gate outcome.

Usage
-----
    python exp/exp_2_run.py
"""

import json
import logging
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

# ---------------------------------------------------------------------------
# Ensure project root is on sys.path so src/ imports resolve
# ---------------------------------------------------------------------------
_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from src.liquid_universe_extension import run_liquid_extension_pipeline

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s – %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("exp_2")

RESULTS_DIR = _ROOT / "results" / "exp2"
DATA_CACHE = _ROOT / "data" / "cache"


# ---------------------------------------------------------------------------
# Persistence helpers
# ---------------------------------------------------------------------------

def _save_dataframe(df: pd.DataFrame, name: str) -> None:
    """Save *df* as both CSV and Parquet to RESULTS_DIR."""
    if df.empty:
        logger.warning("DataFrame '%s' is empty; skipping save.", name)
        return
    csv_path = RESULTS_DIR / f"{name}.csv"
    df.to_csv(csv_path, index=False)
    logger.info("Saved %s → %s (%d rows)", name, csv_path, len(df))


def _save_json(data: dict, name: str) -> None:
    """Save a JSON-serialisable dict to RESULTS_DIR."""
    out = RESULTS_DIR / f"{name}.json"
    with open(out, "w") as f:
        json.dump(data, f, indent=2, default=str)
    logger.info("Saved %s → %s", name, out)


def _write_exp2_report(results: dict) -> None:
    """Write a markdown summary of exp_2 results."""
    gate_passed = results.get("gate_passed", False)
    coverage = results.get("coverage_fraction", 0.0)
    sched = results.get("scheduler_summary", {})
    screened = results.get("screened_events", pd.DataFrame())
    matched = results.get("matched_controls", pd.DataFrame())

    gate_icon = "✅ PASSED" if gate_passed else "❌ FAILED"

    lines = [
        "# Exp-2: Liquid Universe Extension – Results",
        "",
        "> Auto-generated by `exp/exp_2_run.py`",
        "",
        "---",
        "",
        "## ⚡ Matched-Control Support Gate",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Coverage fraction | {coverage:.3f} ({coverage*100:.1f}%) |",
        f"| Threshold | 0.80 (80%) |",
        f"| **Gate result** | **{gate_icon}** |",
        "",
    ]

    if not gate_passed:
        lines += [
            "> ⚠️  **Warning**: Coverage below 80 % threshold.  Causal inference from",
            "> matched-control comparisons should be treated with caution.",
            "> Consider expanding the control universe or relaxing match-variable tolerances.",
            "",
        ]

    lines += [
        "---",
        "",
        "## Liquid Universe Screen",
        "",
        f"- Events after screening: **{len(screened):,}**",
        f"- Distinct tickers: **{screened['ticker'].nunique() if 'ticker' in screened.columns else 'N/A'}**",
        "",
        "## Scheduler Summary",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Scheduled notional ($) | {sched.get('scheduled_notional', 0):,.0f} |",
        f"| Avg capital deployed ($) | {sched.get('avg_capital_use', 0):,.0f} |",
        f"| Peak capital deployed ($) | {sched.get('peak_capital_use', 0):,.0f} |",
        f"| Annualised turnover (×) | {sched.get('annualised_turnover', 0):.2f} |",
        f"| Total position count | {sched.get('n_positions_total', 0):,} |",
        "",
        "## Matched Controls",
        "",
        f"- Matched pairs: **{len(matched):,}**",
        f"- Events with ≥1 match: **{matched['event_id'].nunique() if not matched.empty else 0}**",
        "",
        "---",
        f"_Report generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')} UTC_",
    ]

    out_path = RESULTS_DIR / "RESULTS_exp2.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Exp-2 report written to %s", out_path)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    DATA_CACHE.mkdir(parents=True, exist_ok=True)

    start_ts = datetime.utcnow()
    logger.info("=" * 60)
    logger.info("Exp-2 pipeline started at %s", start_ts.isoformat())
    logger.info("=" * 60)

    results = run_liquid_extension_pipeline(cache_dir=str(DATA_CACHE))

    # ------------------------------------------------------------------ Save
    _save_dataframe(results["screened_events"], "screened_events")
    _save_dataframe(results["matched_controls"], "matched_controls")
    _save_json(results["scheduler_summary"], "scheduler_summary")

    gate_json = {
        "gate_passed": results["gate_passed"],
        "coverage_fraction": results["coverage_fraction"],
    }
    _save_json(gate_json, "support_gate")

    # ------------------------------------------------------------------ Report
    _write_exp2_report(results)

    # ------------------------------------------------------------------ Prominent gate display
    gate_passed = results["gate_passed"]
    coverage = results["coverage_fraction"]
    banner = "=" * 60
    gate_msg = "PASSED ✅" if gate_passed else "FAILED ❌  ← ACTION REQUIRED"
    logger.info(banner)
    logger.info("SUPPORT GATE: %s  (coverage=%.3f)", gate_msg, coverage)
    logger.info(banner)

    end_ts = datetime.utcnow()
    elapsed = (end_ts - start_ts).total_seconds()
    logger.info("Exp-2 pipeline completed in %.1f s.", elapsed)
    logger.info("Results written to: %s", RESULTS_DIR)


if __name__ == "__main__":
    main()
